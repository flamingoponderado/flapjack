#!/usr/bin/env python3
"""Generate a Lean literal for the byte-exact pinned CakeML exporter capture."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'scripts/hol-probes/cake_riscv_export_probe.out'
OUTPUT = ROOT / 'Flapjack/Test/CakeExportOracle.lean'

def generate():
    lines = SOURCE.read_text().splitlines()
    if len(lines) != 2 or not lines[0].startswith('assembly=') or lines[1] != 'end=ok':
        raise ValueError('unexpected exporter capture')
    bs = bytes(int(x) for x in lines[0][len('assembly='):].split(','))
    text = bs.decode('ascii')
    return ('-- Generated by scripts/generate-cake-export-oracle.py.\n'
            'namespace Flapjack.Test.CakeExportOracle\n'
            'def expected : String := ' + json.dumps(text) + '\n'
            'end Flapjack.Test.CakeExportOracle\n')

if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
    result = generate()
    if a.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result: raise SystemExit('export oracle is stale')
        print('CakeML exporter oracle matches pinned HOL bytes')
    else: OUTPUT.write_text(result)
