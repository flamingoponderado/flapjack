#!/usr/bin/env python3
"""Render the pinned CakeML/HOL flat-pass observations as Lean constants."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "scripts/hol-probes/cakeml_frontend_flat_probe.out"
OUTPUT = ROOT / "Flapjack/Test/CakeMLFlatOracle.lean"
NAMES = ("name_roundtrips", "name_bytes", "name_unreserved", "pure_init", "hidden_init",
         "impure_lookup_init", "hidden_lookup_init", "keep_empty", "keep_reachable",
         "eliminate_pure_length", "eval_bypass_length", "guard_double_not", "guard_false_conj",
         "pattern_encoding", "empty_program_globals", "empty_program_output", "word8_literal",
         "smart_constructor", "int_division", "copy_string", "array_update", "word8_conversion",
         "compile_let", "compile_constructor", "compile_nop", "closure_empty_program",
         "closure_install_detect", "closure_init_false", "incremental_empty", "interpreter_arity",
         "pattern_any_tree", "pattern_constructor_guard", "pattern_nub", "pattern_specialize",
         "pattern_compile_empty", "pattern_compile_any", "pattern_exhaustive", "pattern_bind_variable", "pattern_compile_branch", "pattern_naive_branch", "pattern_constructor_branch",
         "empty_source_to_clos", "reference_source_to_clos", "source_let_lifting", "lifted_source_to_clos", "match_source_to_clos", "match_bind_source_to_clos",
         "bvl_shared_constant", "bvl_stub_layout", "bvl_chain_empty", "bvl_code_sort", "bvl_build_aux", "bvl_source_names",
         "closure_numbering", "closure_number_incremental", "bvl_closure_call", "bvl_partial_application", "bvl_extract_name", "bvl_name_alist", "bvl_recursive_closures", "bvl_compile_closure", "bvl_compile_program", "bvl_to_bvi_analysis", "bvl_to_bvi_operations", "bvi_let_optimization", "bvl_to_bvi_marker", "bvl_to_bvi_incremental", "clos_to_bvi_program", "data_lang_syntax", "data_space_requirements", "bvi_to_data_assign", "bvi_to_data_expression", "data_simplification", "data_liveness", "data_optimisation", "bvi_to_data_complete_example", "clos_to_data_program", "data_to_word_variables", "data_to_word_header", "data_to_word_locations", "data_to_word_word_ops", "data_to_word_control", "clos_to_word_control", "data_to_word_space", "data_to_word_assign", "clos_to_bvi_constant", "bvi_to_data_constant", "data_to_word_globals", "data_to_word_loads", "data_to_word_ref", "data_to_word_int", "data_to_word_comparisons", "data_to_word_byte_ops", "data_to_word_byte_shifts", "bvl_to_bvi_stubs", "bvl_to_bvi_whole_program", "bvl_to_bvi_stub_bodies", "bvl_closure_stubs", "bvl_prepared_program", "bvl_force_thunk", "db_vars_order", "closure_free_variables", "closure_annotation", "closure_no_options_program", "closure_no_options_function", "empty_cake_to_bvi")


def render():
    rows = dict(line.split("=", 1) for line in INPUT.read_text().splitlines())
    if set(rows) != set(NAMES):
        raise ValueError("unexpected or missing HOL oracle rows")
    nums = rows["name_roundtrips"]
    if not (nums.startswith("[") and nums.endswith("]")):
        raise ValueError("invalid HOL list")
    numbers = [int(x.strip()) for x in nums[1:-1].split(";")]
    layout = ast.literal_eval(rows["bvl_stub_layout"].replace(";", ","))
    if not isinstance(layout, list) or not all(type(n) is int and n >= 0 for n in layout):
        raise ValueError("invalid BVL stub layout")
    byte_rows = ast.literal_eval(rows["name_bytes"].replace(";", ","))
    if not isinstance(byte_rows, list) or not all(
        isinstance(row, list) and all(type(b) is int and 0 <= b <= 255 for b in row)
        for row in byte_rows
    ):
        raise ValueError("invalid encoded-name byte rows")
    name_unreserved = int(rows["name_unreserved"])
    lines = ["-- Generated by scripts/generate-cakeml-flat-oracle.py; do not edit.",
             "namespace Flapjack.Test.CakeMLFlatOracle",
             f"def nameRoundtrips : List Nat := {numbers}",
             f"def nameBytes : List (List Nat) := {byte_rows}",
             f"def bvl_stub_layout : List Nat := {layout}",
             f"def nameUnreserved : Nat := {name_unreserved}"]
    if rows["interpreter_arity"] not in ("[F; T]", "[F; F]", "[T; F]", "[T; T]"):
        raise ValueError("invalid interpreter arity observations")
    values = rows["interpreter_arity"][1:-1].split("; ")
    lines.append(f"def interpreter_arity : List Bool := [{', '.join('true' if v == 'T' else 'false' for v in values)}]")
    exhaustive = rows["pattern_exhaustive"]
    if not (exhaustive.startswith("[") and exhaustive.endswith("]")):
        raise ValueError("invalid exhaustiveness observations")
    values = exhaustive[1:-1].split("; ")
    if len(values) != 4 or any(v not in ("T", "F") for v in values):
        raise ValueError("invalid exhaustiveness observations")
    lines.append(f"def pattern_exhaustive : List Bool := [{', '.join('true' if v == 'T' else 'false' for v in values)}]")
    for name in ("pure_init", "hidden_init", "impure_lookup_init", "hidden_lookup_init",
                 "keep_empty", "keep_reachable", "guard_double_not", "guard_false_conj",
                 "pattern_encoding", "empty_program_output", "word8_literal", "smart_constructor",
                 "int_division", "copy_string", "array_update", "word8_conversion", "compile_let",
                 "compile_constructor", "compile_nop", "closure_empty_program", "closure_install_detect",
                 "closure_init_false", "incremental_empty", "pattern_any_tree", "pattern_constructor_guard",
                 "pattern_nub", "pattern_specialize", "pattern_compile_empty", "pattern_compile_any",
                 "pattern_bind_variable", "pattern_compile_branch", "pattern_naive_branch", "pattern_constructor_branch", "empty_source_to_clos", "reference_source_to_clos",
                 "source_let_lifting", "lifted_source_to_clos", "match_source_to_clos", "match_bind_source_to_clos", "bvl_shared_constant", "bvl_chain_empty", "bvl_code_sort", "bvl_build_aux", "bvl_source_names", "closure_numbering", "closure_number_incremental", "bvl_closure_call", "bvl_partial_application", "bvl_extract_name", "bvl_name_alist", "bvl_recursive_closures", "bvl_compile_closure", "bvl_compile_program", "bvl_to_bvi_analysis", "bvl_to_bvi_operations", "bvi_let_optimization", "bvl_to_bvi_marker", "bvl_to_bvi_incremental", "clos_to_bvi_program", "data_lang_syntax", "data_space_requirements", "bvi_to_data_assign", "bvi_to_data_expression", "data_simplification", "data_liveness", "data_optimisation", "bvi_to_data_complete_example", "clos_to_data_program", "data_to_word_variables", "data_to_word_header", "data_to_word_locations", "data_to_word_word_ops", "data_to_word_control", "clos_to_word_control", "data_to_word_space", "data_to_word_assign", "clos_to_bvi_constant", "bvi_to_data_constant", "data_to_word_globals", "data_to_word_loads", "data_to_word_ref", "data_to_word_int", "data_to_word_comparisons", "data_to_word_byte_ops", "data_to_word_byte_shifts", "bvl_to_bvi_stubs", "bvl_to_bvi_whole_program", "bvl_to_bvi_stub_bodies", "bvl_closure_stubs", "bvl_prepared_program", "bvl_force_thunk", "db_vars_order", "closure_free_variables", "closure_annotation", "closure_no_options_program", "closure_no_options_function", "empty_cake_to_bvi"):
        value = rows[name]
        if value not in ("T", "F"):
            raise ValueError(f"invalid HOL boolean for {name}: {value}")
        lines.append(f"def {name} : Bool := {'true' if value == 'T' else 'false'}")
    for name in ("eliminate_pure_length", "eval_bypass_length", "empty_program_globals"):
        lines.append(f"def {name} : Nat := {int(rows[name])}")
    return "\n".join(lines + ["end Flapjack.Test.CakeMLFlatOracle", ""])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit(f"{OUTPUT} is stale; regenerate it from the HOL capture")
        print("CakeML flat oracle fixture matches the captured HOL output")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
