#!/usr/bin/env python3
"""Render the pinned CakeML/HOL flat-pass observations as Lean constants."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "scripts/hol-probes/cakeml_frontend_flat_probe.out"
OUTPUT = ROOT / "Flapjack/Test/CakeMLFlatOracle.lean"
NAMES = ("name_roundtrips", "name_bytes", "name_unreserved", "pure_init", "hidden_init",
         "impure_lookup_init", "hidden_lookup_init", "keep_empty", "keep_reachable",
         "eliminate_pure_length", "eval_bypass_length", "guard_double_not", "guard_false_conj",
         "pattern_encoding")


def render():
    rows = dict(line.split("=", 1) for line in INPUT.read_text().splitlines())
    if set(rows) != set(NAMES):
        raise ValueError("unexpected or missing HOL oracle rows")
    nums = rows["name_roundtrips"]
    if not (nums.startswith("[") and nums.endswith("]")):
        raise ValueError("invalid HOL list")
    numbers = [int(x.strip()) for x in nums[1:-1].split(";")]
    byte_rows = ast.literal_eval(rows["name_bytes"].replace(";", ","))
    if not isinstance(byte_rows, list) or not all(
        isinstance(row, list) and all(type(b) is int and 0 <= b <= 255 for b in row)
        for row in byte_rows
    ):
        raise ValueError("invalid encoded-name byte rows")
    name_unreserved = int(rows["name_unreserved"])
    lines = ["-- Generated by scripts/generate-cakeml-flat-oracle.py; do not edit.",
             "namespace Flapjack.Test.CakeMLFlatOracle",
             f"def nameRoundtrips : List Nat := {numbers}",
             f"def nameBytes : List (List Nat) := {byte_rows}",
             f"def nameUnreserved : Nat := {name_unreserved}"]
    for name in NAMES[3:-5] + NAMES[-3:]:
        value = rows[name]
        if value not in ("T", "F"):
            raise ValueError(f"invalid HOL boolean for {name}: {value}")
        lines.append(f"def {name} : Bool := {'true' if value == 'T' else 'false'}")
    for name in NAMES[-5:-3]:
        lines.append(f"def {name} : Nat := {int(rows[name])}")
    return "\n".join(lines + ["end Flapjack.Test.CakeMLFlatOracle", ""])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit(f"{OUTPUT} is stale; regenerate it from the HOL capture")
        print("CakeML flat oracle fixture matches the captured HOL output")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
