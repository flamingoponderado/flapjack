#!/usr/bin/env python3
"""Render CakeML's generated grammar carrier from the pinned HOL capture."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "scripts/hol-probes/cake_nonterminals_probe.out"
OUTPUT = ROOT / "Flapjack/CakeParser/Nonterminal.lean"


def render():
    row = INPUT.read_text().strip()
    if not row.startswith("constructors="):
        raise ValueError("missing generated HOL nonterminal constructors")
    names = row[len("constructors="):].split(",")
    if not names or len(names) != len(set(names)) or any(not re.fullmatch(r"n[A-Za-z0-9_]+", n) for n in names):
        raise ValueError("invalid generated HOL nonterminal constructors")
    constructors = "\n".join(f"  | {name}" for name in names)
    return f'''-- Generated from the pinned HOL grammar's MMLnonT constructors; do not edit.
import Flapjack.HolRef

namespace Flapjack.CakeParser

/-- Constructor-for-constructor rendering of `MMLnonT`, generated by HOL's
`mk_grammar_def` in `cakeml/semantics/gramScript.sml`. There is no syntactic
HOL datatype declaration to cite with `@[hol]`; the checked-in probe records
the constructors and order of the generated carrier. -/
inductive Nonterminal where
{constructors}
  deriving DecidableEq, Repr

end Flapjack.CakeParser
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            raise SystemExit(f"{OUTPUT} is stale; regenerate it from the HOL capture")
        print("CakeML nonterminal carrier matches the captured HOL constructors")
    else:
        OUTPUT.write_text(output)


if __name__ == "__main__":
    main()
