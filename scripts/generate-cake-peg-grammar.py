#!/usr/bin/env python3
"""Translate the pinned first-order CakeML grammar, rejecting unfamiliar syntax."""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'cakeml/compiler/parsing/pegexec_cml_foScript.sml'
OUTPUT = ROOT / 'Flapjack/CakeParser/PegGrammar.lean'
ARITY = {'Seq_fo': 3, 'Choice_fo': 2, 'Rpt_fo': 1, 'Tok_fo': 2,
         'Nt_fo': 2, 'Empty_fo': 1, 'INL': 1, 'TokenCheck_eq': 1,
         'TokenCheck_alpha': 1, 'TokenCheck_symbol': 1, 'TokenCheck_longid': 1,
         'TokenMap_bindNT': 1, 'SemU_bindNT': 1, 'SemB_bindNT0': 1,
         'SemB_mklinfix': 1, 'AlphaT': 1, 'SymbolT': 1}
MAP = {'Seq_fo': '.seq', 'Choice_fo': '.choice', 'Rpt_fo': '.repeat',
       'Tok_fo': '.token', 'Nt_fo': '.nt', 'Empty_fo': '.empty', 'INL': 'Sum.inl',
       'TokenCheck_eq': '.eq', 'TokenCheck_alpha': '.alpha', 'TokenCheck_symbol': '.symbol',
       'TokenCheck_longid': '.longid', 'TokenMap_bindNT': '.bindNT',
       'TokenMap_mktokLf': '.leaf', 'TokenMap_empty_list': '.empty',
       'SemU_bindNT': '.bindNT', 'SemU_id': '.id', 'SemB_bindNT0': '.bindNT0',
       'SemB_mklinfix': '.mkLinfix', 'SemB_append': '.append',
       'SemB_foldl_Eapp': '.foldEapp', 'SemB_foldl_DType': '.foldDType',
       'SemB_papp_ctor_rpt': '.pappCtor', 'SemB_ebase_paren_apply': '.ebaseParen',
       'TokenAlpha_lower_initial_not_reserved': '.lowerInitialNotReserved',
       'TokenAlpha_upper_initial': '.upperInitial', 'TokenAlpha_nonempty': '.nonempty',
       'TokenLongid_tail_nonempty_head_alpha_not_upper': '.tailNonemptyHeadAlphaNotUpper',
       'TokenLongid_ctor_upper_initial': '.ctorUpperInitial',
       'TokenSymbol_valid_prefix': '.validPrefix', 'TokenSymbol_valid_mult': '.validMult',
       'TokenSymbol_valid_add': '.validAdd', 'TokenSymbol_valid_rel': '.validRel',
       'TokenSymbol_valid_list': '.validList', 'TokenCheck_isInt': '.isInt',
       'TokenCheck_isString': '.isString', 'TokenCheck_isChar': '.isChar',
       'TokenCheck_isWord': '.isWord', 'TokenCheck_isFFI': '.isFfi',
       'TokenCheck_isTyvarT': '.isTyvar', 'TokenCheck_isAlphaSym': '.isAlphaSym',
       'TokenCheck_isLongidT': '.isLongid', 'TokenCheck_opid_longid_nonempty': '.opidLongidNonempty',
       'TokenCheck_opid_symbol_nonempty': '.opidSymbolNonempty',
       'TokenCheck_opid_alpha_nonempty': '.opidAlphaNonempty',
       'AlphaT': '.alphaT', 'SymbolT': '.symbolT'}
TOKEN = re.compile(r'\s*(«[^»]*»|[A-Za-z_][A-Za-z0-9_]*|[()\[\]=∧])')

def generate():
    source = SOURCE.read_text().split('Definition nt_rule_fo_def:', 1)[1].split('\nEnd', 1)[0]
    tokens = []
    while source.strip():
        m = TOKEN.match(source)
        if not m:
            raise ValueError('unrecognized source: ' + repr(source[:80]))
        tokens.append(m.group(1)); source = source[m.end():]
    pos = 0
    def take(expected=None):
        nonlocal pos
        t = tokens[pos]; pos += 1
        if expected is not None and t != expected: raise ValueError((expected, t, pos))
        return t
    def expr():
        t = take()
        if t == '(':
            e = expr(); take(')'); return e
        if t == '[':
            take(']'); return '[]'
        if t.startswith('«'):
            return '(ofString ' + repr(t[1:-1]).replace("'", '"') + ')'
        if t in MAP:
            args = [expr() for _ in range(ARITY.get(t, 0))]
            return '(' + ' '.join([MAP[t]] + args) + ')' if args else MAP[t]
        if t.startswith('n') and len(t) > 1 and t[1].isupper(): return '.' + t
        if t.endswith('T') and t[0].isupper(): return '.' + t[0].lower() + t[1:]
        raise ValueError(('unrecognized expression', t, pos))
    branches = []
    while True:
        take('nt_rule_fo')
        if tokens[pos] == '_':
            take('_'); take('='); take('NONE'); break
        take('('); take('INL'); name = take(); take(')'); take('='); take('SOME')
        branches.append((name, expr()))
        take('∧')
    if pos != len(tokens) or len(branches) != 69 or len({n for n, _ in branches}) != 69:
        raise ValueError('unexpected grammar shape')
    header = '''-- Generated by scripts/generate-cake-peg-grammar.py; do not edit.\nimport Flapjack.CakeParser.PegSyntax\n\nnamespace Flapjack.CakeParser.PegGrammar\nopen Flapjack.Basis.Pure.MlString PegSyntax\n\n/-- The complete first-order CakeML grammar, including the default failure rule. -/\n@[hol "cakeml/compiler/parsing/pegexec_cml_foScript.sml" "nt_rule_fo_def"]\ndef ntRule : Rule → Option PegExpr\n'''
    return header + ''.join(f'  | .inl .{n} => some {e}\n' for n,e in branches) + '  | _ => none\n\nend Flapjack.CakeParser.PegGrammar\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result: raise SystemExit('generated grammar is stale')
    else: OUTPUT.write_text(result)
